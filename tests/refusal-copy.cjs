'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('index.html','utf8');
const code=source.match(/function diagnosticReason\(r\)\{[\s\S]*?\n\}/);
assert.ok(code,'Shared presentation helper exists');
const reason=vm.runInNewContext('('+code[0]+')');
const fixture=JSON.parse(fs.readFileSync('tests/fixtures/museum-refusal-copy-v1.json','utf8'));
const original=JSON.stringify(fixture);
assert.equal(fixture.eligible_nonempty_corpus_records,1);
assert.equal(fixture.displayed_supporting_source_count_for_closing,0);
assert.match(reason(fixture.cases.closing),/requested field/);
assert.match(reason(fixture.cases.closing),/Other eligible passages may still exist/);
assert.match(reason(fixture.cases.closing),/not a corpus-wide passage count/);
assert.equal(reason(fixture.cases.opening),fixture.cases.opening.answer_contract.diagnostic.message);
assert.equal(JSON.stringify(fixture),original,'Rendering must not mutate reader decisions');
const grammar={answer_diagnostics:{category:'unsupported_question_grammar',message:'Unsupported form.'}};
assert.match(reason(grammar),/source may contain an answer/i);
const budget={answer_contract:{answer_supported:false,diagnostic:{category:'index_exhaustion',message:'Budget stopped.'}}};
assert.match(reason(budget),/not established within the budget/);
const unavailable={answer_diagnostics:{category:'absent_eligible_source',message:'No pages can be served under this profile.'}};
assert.equal(reason(unavailable),unavailable.answer_diagnostics.message);
const conflict={answer_diagnostics:{category:'known_source_conflict',message:'Conflicting or multiple eligible owners; no winner chosen.'}};
assert.equal(reason(conflict),conflict.answer_diagnostics.message);
assert.equal((source.match(/esc\(diagnosticReason\(r\)\)/g)||[]).length,2,'Both result renderers use the same copy rule');
console.log('PASS: diagnostic-driven museum copy; native decisions unchanged; synthetic software fixture only.');
