"""Gremlin: read-only repository relationships, drift and change-review hints.

Run with ``python -m test_tools.gremlin``. Only ``refresh`` writes the two generated
map files. Nothing here executes a component, opens an archive or dispatches an
effect. The map is a maintenance index, not source-ledger or authority evidence.
"""
import argparse
from collections import deque
import hashlib
import json
from pathlib import Path, PurePosixPath
import subprocess

from tools.audit_departments import DEPARTMENTS, department_for

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = 'docs/gremlin/registry.json'
OUTPUTS = ('docs/gremlin/map.json', 'docs/gremlin/MAP.md')
# Exclude generated/self-containing coordination bytes, not their path names.
EXCLUDED_CONTENT = set(OUTPUTS) | {
    'HANDOFF.md', 'handoff/manifest.json', 'handoff/update.json',
}
SCOPES = {'product', 'project', 'data', 'experiment'}
RELATIONS = {'depends_on', 'uses_data', 'tested_by', 'records', 'possible_reuse'}
BASES = {'source', 'documentation', 'proposal'}


def encoded(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=False).encode()


def sha(value):
    return hashlib.sha256(value).hexdigest()


def relative(name):
    if not isinstance(name, str) or not name or '\\' in name:
        raise ValueError('Invalid repository path')
    p = PurePosixPath(name)
    if p.is_absolute() or any(x in {'..', '.git'} for x in p.parts) or p.as_posix() != name:
        raise ValueError('Unsafe or noncanonical repository path: ' + name)
    return name


def safe(root, name):
    path = root / relative(name)
    path.resolve().relative_to(root.resolve())
    if path.is_symlink():
        raise ValueError('Symlink cannot establish a map source: ' + name)
    return path


def tracked(root):
    if (root / '.git').exists():
        raw = subprocess.check_output(['git', 'ls-files', '-z'], cwd=root)
        return sorted(set(raw.decode().split('\0')) - {''})
    manifest = json.loads((root / 'handoff/manifest.json').read_text())
    return sorted(set(manifest['files']) | {'HANDOFF.md', 'handoff/manifest.json'})


def fingerprint(path):
    h = hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def under(name, prefix):
    return prefix == '.' or name == prefix or name.startswith(prefix + '/')


def study_rows(rows):
    for row in rows:
        yield row
        yield from study_rows(row.get('subfamilies', []))


def build(root=ROOT, names=None):
    root = Path(root)
    names = tracked(root) if names is None else sorted(set(names))
    for name in names:
        relative(name)
    membership = set(names)
    registry = json.loads(safe(root, REGISTRY).read_text())
    ownership = json.loads(safe(root, 'docs/departments/components.json').read_text())
    results = json.loads(safe(root, 'docs/results.json').read_text())
    if registry.get('schema') != 'gremlin-registry-v1':
        raise ValueError('Unknown Gremlin registry')
    if ownership.get('schema') != 'department-navigation-v1' or results.get('schema') != 'result-test-index-v1':
        raise ValueError('Unknown authoritative index schema')
    if set(registry['departments']) != DEPARTMENTS:
        raise ValueError('Department annotations must cover the authoritative departments')

    groups = {department: [] for department in DEPARTMENTS}
    unmapped = []
    for name in names:
        try:
            owner = department_for(name, ownership)
            groups[owner].append(name)
        except KeyError:
            unmapped.append(name)
    if unmapped:
        raise ValueError('Unmapped ownership; review the department index: ' + ', '.join(unmapped[:12]))

    hashes = {}

    def digest_for(paths):
        selected = [p for p in paths if p not in EXCLUDED_CONTENT]
        for p in selected:
            if p not in hashes:
                hashes[p] = fingerprint(safe(root, p))
        return sha(encoded([[p, hashes[p]] for p in selected]))

    def evidence(paths):
        if not paths:
            raise ValueError('Map assertions need evidence references')
        refs = []
        for p in paths:
            if p not in membership or p in EXCLUDED_CONTENT:
                raise ValueError('Evidence must name tracked, non-generated bytes: ' + p)
            if p not in hashes:
                hashes[p] = fingerprint(safe(root, p))
            refs.append({'path': p, 'sha256': hashes[p]})
        return refs

    nodes = {}

    def add_node(node):
        id = node['id']
        if id in nodes:
            raise ValueError('Duplicate component ID: ' + id)
        if not node['scopes'] or not set(node['scopes']) <= SCOPES or len(set(node['scopes'])) != len(node['scopes']):
            raise ValueError('Invalid responsibility scopes: ' + id)
        nodes[id] = node

    for id, paths in sorted(groups.items()):
        annotation = registry['departments'][id]
        add_node({'id': id, 'kind': 'department', 'label': annotation['label'],
                  'scopes': annotation['scopes'], 'status': annotation['status'],
                  'note': annotation['note'], 'paths': [], 'tracked_files': len(paths),
                  'content_sha256': digest_for(paths),
                  'evidence': evidence(['docs/departments/' + id + '.md'])})

    for row in registry['components']:
        prefixes = [relative(p) for p in row['paths']]
        for p in prefixes:
            if not any(under(n, p) for n in names):
                raise ValueError('Component path has no tracked files: ' + p)
        selected = [n for n in names if any(under(n, p) for p in prefixes)]
        if not selected and row['status'] != 'proposed':
            raise ValueError('Only proposed components may have no implementation: ' + row['id'])
        add_node({**row, 'kind': 'component', 'tracked_files': len(selected),
                  'content_sha256': digest_for(selected), 'evidence': evidence(row['evidence'])})

    edges = []
    for row in study_rows(results['families']):
        id = 'study:' + row['family']
        prefix = relative(row['artifacts'])
        selected = [n for n in names if under(n, prefix)]
        # Keep scores and status wording in their authoritative index, not a new grade.
        add_node({'id': id, 'kind': 'study', 'label': row['family'],
                  'scopes': ['data', 'experiment'], 'status': 'indexed-evidence',
                  'paths': [prefix], 'tracked_files': len(selected),
                  'scope_from_index': row['scope'], 'status_from_index': row['measurement_status'],
                  'status_authority': 'docs/results.json; may describe a historical pin',
                  'content_sha256': digest_for(selected),
                  'evidence': evidence(['docs/results.json']),
                  'tests': row['tests'], 'runners': row['runners']})
        for p in [prefix] + row['tests'] + row['runners']:
            relative(p)
            if not any(under(n, p) for n in names):
                raise ValueError('Indexed study path has no tracked files: ' + p)
        for department in row.get('implementation_departments', []):
            if department not in DEPARTMENTS:
                raise ValueError('Study references unknown department: ' + department)
            edges.append({'from': department, 'to': id, 'kind': 'tested_by',
                          'basis': 'documentation', 'note': 'Indexed coverage link, not a passed check.',
                          'evidence': evidence(['docs/results.json'])})

    edge_keys = set()
    for edge in registry['relations']:
        if edge['from'] not in nodes or edge['to'] not in nodes:
            raise ValueError('Relation references an unknown component')
        if edge['kind'] not in RELATIONS or edge['basis'] not in BASES:
            raise ValueError('Unknown relation kind or evidence basis')
        key = (edge['from'], edge['to'], edge['kind'])
        if key in edge_keys:
            raise ValueError('Duplicate relation: ' + str(key))
        edge_keys.add(key)
        edges.append({**edge, 'evidence': evidence(edge['evidence'])})

    questions = []
    question_ids = set()
    for question in registry['open_work']:
        if question['id'] in question_ids or question['component'] not in nodes:
            raise ValueError('Duplicate open-work ID or unknown component')
        if not question['question'] or not question['revisit_when']:
            raise ValueError('Open work needs a question and revisit condition')
        question_ids.add(question['id'])
        questions.append({**question, 'evidence': evidence(question['evidence'])})

    return {'schema': 'gremlin-map-v1', 'reviewed_on': registry['reviewed_on'],
            'inspected_revision': registry['inspected_revision'],
            'meaning': 'Maintenance index. Links and impact hints confer no evidence, release status or authority.',
            'tracked_paths': len(names), 'pathset_sha256': sha(encoded(names)),
            'ownership_index': 'docs/departments/components.json',
            'evidence_index': 'docs/results.json',
            'content_exclusions': sorted(EXCLUDED_CONTENT),
            'nodes': [nodes[id] for id in sorted(nodes)],
            'relations': sorted(edges, key=lambda e: (e['from'], e['kind'], e['to'])),
            'open_work': sorted(questions, key=lambda q: q['id'])}


def render(report):
    rows = ['# Gremlin active system map', '', 'Last reviewed: ' + report['reviewed_on'] + '.', '',
            'Generated by `python -m test_tools.gremlin refresh`; do not edit this view.', '',
            '[Usage and boundaries](README.md) · [Machine map](map.json) · [Curated registry](registry.json)', '',
            report['meaning'], '',
            f"Tracks {report['tracked_paths']} paths; components can overlap. File counts are not test counts.", '',
            '## Components and responsibilities', '',
            '| ID | Product / project / data / experiment | Declared status | Files |',
            '|---|---|---|---:|']
    for node in report['nodes']:
        if node['kind'] != 'study':
            rows.append(f"| `{node['id']}` | {', '.join(node['scopes'])} | {node['status']} | {node['tracked_files']} |")
    rows.extend(['', '## Curated relationships', '',
                 'Source and documentation references require human interpretation; existence and hashes do not prove a relationship.', ''])
    for edge in report['relations']:
        if edge['kind'] == 'tested_by' and edge['to'].startswith('study:'):
            continue
        refs = ', '.join('[' + Path(e['path']).name + '](../../' + e['path'] + ')' for e in edge['evidence'])
        rows.append(f"- `{edge['from']}` → **{edge['kind']}** → `{edge['to']}` ({edge['basis']}): {edge['note']} {refs}")
    rows.extend(['', '## Indexed experiments', '',
                 'Scopes, original status strings, tests and runners are imported into map.json from [the existing result index](../results.json).',
                 'They retain their historical scope; Gremlin does not rerun or regrade them.', ''])
    rows.append(', '.join('`' + n['id'] + '`' for n in report['nodes'] if n['kind'] == 'study'))
    rows.extend(['', '## Work to remember and revisit', ''])
    for question in report['open_work']:
        refs = ', '.join('[' + Path(e['path']).name + '](../../' + e['path'] + ')' for e in question['evidence'])
        rows.extend([f"### {question['id']}: {question['component']}", '',
                     question['question'], '', 'Revisit when: ' + question['revisit_when'], '', refs, ''])
    return '\n'.join(rows).rstrip() + '\n'


def impact(report, paths, root=ROOT):
    nodes = {n['id']: n for n in report['nodes']}
    mapping = json.loads((Path(root) / 'docs/departments/components.json').read_text())
    direct = set()
    unknown = []
    for path in paths:
        path = relative(path)
        try:
            direct.add(department_for(path, mapping))
        except KeyError:
            unknown.append(path)
        direct.update(n['id'] for n in nodes.values() if any(under(path, p) for p in n['paths']))
    affected = set(direct)
    queue = deque(direct)
    dependencies = [e for e in report['relations'] if e['kind'] in {'depends_on', 'uses_data'} and e['basis'] != 'proposal']
    while queue:
        target = queue.popleft()
        for edge in dependencies:
            if edge['to'] == target and edge['from'] not in affected:
                affected.add(edge['from'])
                queue.append(edge['from'])
    return {'schema': 'gremlin-impact-v1', 'paths': paths, 'direct': sorted(direct),
            'potential_dependents': sorted(affected - direct), 'unmapped_paths': unknown,
            'review_relations': [e for e in report['relations'] if e['from'] in affected or e['to'] in affected],
            'open_work': [q for q in report['open_work'] if q['component'] in affected],
            'meaning': 'Conservative review hints from declared links; not exhaustive, not authorization, and not evidence a test passed.'}


def check_outputs(root, report):
    outputs = (json.dumps(report, indent=2, ensure_ascii=False) + '\n', render(report))
    for name, body in zip(OUTPUTS, outputs):
        if (Path(root) / name).read_text() != body:
            raise ValueError('Stale Gremlin map: review registry and run python -m test_tools.gremlin refresh')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['refresh', 'check', 'show', 'impact'])
    parser.add_argument('items', nargs='*', help='Component IDs for show; repository paths for impact')
    args = parser.parse_args()
    try:
        if args.command in {'show', 'impact'}:
            report = json.loads((ROOT / OUTPUTS[0]).read_text())
            if report.get('schema') != 'gremlin-map-v1':
                raise ValueError('Unknown saved map schema; refresh and check first')
            notice = {'snapshot_only': True, 'freshness': 'Not rechecked by this query; run check before relying on the snapshot.'}
            if args.command == 'show':
                selected = [n for n in report['nodes'] if not args.items or n['id'] in args.items]
                if args.items and set(args.items) - {n['id'] for n in selected}:
                    raise ValueError('Unknown component ID')
                print(json.dumps({**notice, 'nodes': selected}, indent=2))
            else:
                if not args.items:
                    raise ValueError('impact requires at least one repository path')
                print(json.dumps({**notice, **impact(report, args.items)}, indent=2))
            return
        report = build()
        outputs = (json.dumps(report, indent=2, ensure_ascii=False) + '\n', render(report))
        if args.command == 'refresh':
            for name, body in zip(OUTPUTS, outputs):
                (ROOT / name).write_text(body)
            print('Refreshed Gremlin: ' + str(report['tracked_paths']) + ' paths')
        elif args.command == 'check':
            check_outputs(ROOT, report)
            print('PASS current Gremlin map; no runtime tests or permissions inferred')
    except (ValueError, KeyError, OSError, TypeError) as exc:
        parser.exit(1, str(exc) + '\n')


if __name__ == '__main__':
    main()
